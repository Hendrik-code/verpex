class SMDenseNet(nn.Module):
    """Submanifold DenseNet.

    With a SubmDenseNet, directly regress landmark coordinate estimates and landmark-wise features for refinement.
    """

    def __init__(
        self,
        in_channels: int,
        n_landmarks: int,
        loss_fn: str,
        project_gt: bool = False,
        init_features: int = 64,
        feature_l: int = 256,
        growth_rate: int = 32,
        block_config: Sequence[int] = (6, 12, 24, 16),
        bn_size: int = 4,
        dropout_prob: float = 0.0,
        **kwargs,  # noqa: ARG002 - absorbs config keys that other coarse modules use
    ):
        super().__init__()

        self.loss_fn = get_loss_fn(loss_fn)

        # Imported here, not at module scope: subm_densenet subclasses spconv types at
        # class-definition time, so importing it would make spconv a hard dependency
        # of the whole package rather than of these two sparse backbones.
        from verpex.models.subm_densenet import SubmDenseNet

        self.feature_extractor = SubmDenseNet(
            in_channels=in_channels,
            n_landmarks=n_landmarks,
            init_features=init_features,
            feature_l=feature_l,
            growth_rate=growth_rate,
            block_config=block_config,
            bn_size=bn_size,
            dropout_prob=dropout_prob,
        )

        self.project_gt = project_gt

    def forward(self, batch) -> dict:
        """Predict coarse landmark coordinates and features, adding them to ``batch``.

        Args:
            batch: A batch containing the input volume.

        Returns:
            The batch, with ``coarse_preds`` and ``coarse_features`` added.
        """
        x = batch["input"]
        coarse_preds, feature_encodings = self.feature_extractor(x)

        batch["coarse_preds"] = coarse_preds
        batch["coarse_features"] = feature_encodings

        return batch

    def calculate_loss(self, batch) -> torch.Tensor:
        """Return the coarse-stage loss for ``batch``, computed in millimetres."""
        target = batch["target"]
        surface = batch["surface"]
        if self.project_gt:
            target, _ = surface_project_coords(target, surface)

        # Scale to millimetres, as SADenseNet does, so the loss means the same thing
        # at any voxel spacing and is comparable across coarse modules.
        zoom = batch["zoom"].to(target.device).unsqueeze(1)

        return self.loss_fn(
            batch["coarse_preds"] * zoom,
            target * zoom,
            batch["loss_mask"],
            surface,
            # Set by PoiNeighborPredictionModule; absent for single-vertebra batches.
            batch.get("poi_loss_weights"),
        )

    def calculate_metrics(self, batch, mode) -> dict:
        """Return coarse-stage metrics for ``batch``, each name suffixed with ``mode``."""
        metrics = {}

        coarse_preds = batch["coarse_preds"]  # (batch_size, n_landmarks, 3)
        target = batch["target"]  # (batch_size, n_landmarks, 3)
        target_indices = batch["target_indices"]  # (batch_size, n_landmarks)
        loss_mask = batch["loss_mask"]  # (batch_size, n_landmarks)

        if self.project_gt:
            target = batch["target"]
            # Project targets to surface
            surface = batch["surface"]
            target, projection_dist = surface_project_coords(target, surface)

            metrics[f"coarse_projection_dist_{mode}"] = projection_dist.mean()

        # Calculate the mean Euclidean distance between the predicted and target landmarks
        # Millimetres, as in the dense coarse modules, so the numbers logged by
        # the sparse backbones are comparable with everything else.
        zoom = batch["zoom"].to(target.device).unsqueeze(1)
        distances = torch.norm((coarse_preds - target) * zoom, dim=-1)

        distances_mean, distances_std = distances.mean(), distances.std()

        metrics[f"coarse_mean_distance_{mode}"] = distances_mean
